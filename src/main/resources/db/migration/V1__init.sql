-- V1: first version of the database. Flyway runs this ONCE and records it.
-- Never edit this file after it has run; add V2__..., V3__... instead.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,          -- BCrypt hash, never the real password
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('MANAGER', 'STAFF'))
);

CREATE TABLE product (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL UNIQUE,
    category      VARCHAR(50)   NOT NULL,
    unit          VARCHAR(20)   NOT NULL,
    price         NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    stock         INTEGER       NOT NULL CHECK (stock >= 0),   -- last line of defence against overselling
    reorder_level INTEGER       NOT NULL CHECK (reorder_level >= 0),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Every stock change is recorded (like a canteen ledger). Stock = purchases - sales.
CREATE TABLE stock_movement (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT        NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    type        VARCHAR(10)   NOT NULL CHECK (type IN ('PURCHASE', 'SALE')),
    quantity    INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    created_by  VARCHAR(50)   NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Indexes = a book's index: jump straight to the rows instead of reading every page.
-- Dashboard and forecast always ask "sales of product X between date A and B".
CREATE INDEX idx_movement_product_type_time ON stock_movement (product_id, type, created_at);
CREATE INDEX idx_movement_time ON stock_movement (created_at);
CREATE INDEX idx_product_name_lower ON product (lower(name));
